#!/usr/bin/env python3
"""
Generate CubeMX/Makefile.gen from the CubeMX-generated CubeMX/Makefile.

CubeMX (toolchain = Makefile) only knows about ../Src, ../Drivers and
../Middlewares.  This project additionally has a C/C++ user tree under
../userCode which contains the real ``main()`` and all application code.

This script appends that user tree (C and C++), the matching include
directories and the C++ rules to a *copy* of the generated Makefile, so the
original ``Makefile`` stays untouched and can be regenerated at will.

Run:  python3 tools/gen_makefile.py
Then: make -C CubeMX -f Makefile.gen
"""
from __future__ import annotations

import os
import re
from glob import glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # .../LL_Modified
CUBEMX = os.path.join(ROOT, "CubeMX")
SRC_MAKEFILE = os.path.join(CUBEMX, "Makefile")
OUT_MAKEFILE = os.path.join(CUBEMX, "Makefile.gen")


def rel(path: str) -> str:
    """Path relative to the CubeMX dir, POSIX separators."""
    return os.path.relpath(path, CUBEMX).replace(os.sep, "/")


def find(pattern: str) -> list[str]:
    return sorted(rel(p) for p in glob(os.path.join(ROOT, pattern), recursive=True))


# --- user code sources -------------------------------------------------------
uc_c = find("userCode/**/Src/*.c")
uc_cpp = find("userCode/**/Src/*.cpp")
uc_inc = sorted(
    {"-I" + rel(os.path.join(os.path.dirname(os.path.dirname(p)), "Inc"))
     for p in glob(os.path.join(ROOT, "userCode/**/Inc/*.h"), recursive=True)}
)

if not uc_cpp:
    raise SystemExit("no userCode C++ sources found -- wrong working tree?")

with open(SRC_MAKEFILE, encoding="utf-8", errors="replace") as fh:
    text = fh.read()

# Link with g++ so libstdc++ / C++ runtime (__cxa_*, guard variables) are linked.
old_link = "\t$(CC) $(OBJECTS) $(LDFLAGS) -o $@"
new_link = "\t$(CXX) $(OBJECTS) $(LDFLAGS) -o $@"
if old_link not in text:
    raise SystemExit("link line not found -- CubeMX template changed?")
text = text.replace(old_link, new_link, 1)

def mklines(items: list[str], indent: str = " \\\n") -> str:
    return indent.join(items)

block = f"""
###############################################################################
# BEGIN: userCode additions -- generated by tools/gen_makefile.py, do not edit
###############################################################################
# Includes for the user tree
UCODE_INCLUDES = {mklines(uc_inc)}
C_INCLUDES += $(UCODE_INCLUDES)

# C sources from the user tree (e.g. bsp_uart.c)
UCODE_C_SOURCES = {mklines(uc_c) if uc_c else ""}
C_SOURCES += $(UCODE_C_SOURCES)
vpath %.c $(sort $(dir $(UCODE_C_SOURCES)))

# C++ sources from the user tree (contains the real main())
CXX_SOURCES = {mklines(uc_cpp)}
vpath %.cpp $(sort $(dir $(CXX_SOURCES)))
OBJECTS += $(addprefix $(BUILD_DIR)/,$(notdir $(CXX_SOURCES:.cpp=.o)))

# C++ compiler
ifdef GCC_PATH
CXX = $(GCC_PATH)/$(PREFIX)g++
else
CXX = $(PREFIX)g++
endif

CXXFLAGS = $(MCU) $(C_DEFS) $(C_INCLUDES) $(OPT) -Wall -fdata-sections -ffunction-sections
CXXFLAGS += -std=gnu++11 -fno-exceptions -fno-rtti
ifeq ($(DEBUG), 1)
CXXFLAGS += -g -gdwarf-2
endif
CXXFLAGS += -MMD -MP -MF"$(@:%.o=%.d)"

$(BUILD_DIR)/%.o: %.cpp Makefile | $(BUILD_DIR)
\t$(CXX) -c $(CXXFLAGS) -Wa,-a,-ad,-alms=$(BUILD_DIR)/$(notdir $(<:.cpp=.lst)) $< -o $@
###############################################################################
# END: userCode additions
###############################################################################
"""

# The user sources must be registered *before* the "build the application"
# section, because the prerequisites of the .elf rule are expanded eagerly at
# parse time (a plain "$(OBJECTS)" would not see later additions).
marker = "$(BUILD_DIR)/%.o: %.c Makefile | $(BUILD_DIR)"
if marker not in text:
    raise SystemExit("anchor for user sources not found")
text = text.replace(marker, block + "\n" + marker, 1)

with open(OUT_MAKEFILE, "w", encoding="utf-8") as fh:
    fh.write(text)

print(f"wrote {rel(OUT_MAKEFILE)}: {len(uc_c)} C + {len(uc_cpp)} C++ user sources")
for i in uc_inc:
    print("  include", i)
